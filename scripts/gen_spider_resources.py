#!/usr/bin/env python3
"""Regenerate package.json spider media + src/spider_table.inc from spider_catalog.csv."""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "spider_catalog.csv"
PACKAGE = ROOT / "package.json"
SPIDER_INC = ROOT / "src" / "spider_table.inc"


def load_rows() -> list[dict[str, str]]:
    with CATALOG.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def media_entry(name: str, path: str) -> dict:
    return {"type": "bitmap", "name": name, "file": path}


def main() -> None:
    rows = load_rows()
    media: list[dict] = [
        {
            "type": "bitmap",
            "name": "MENU_ICON",
            "file": "images/icon.png",
            "menuIcon": True,
        }
    ]
    inc_lines: list[str] = []

    for row in rows:
        filename = row["filename"]
        mono_name = row["resource"]
        color_name = f"SPIDER_COLOR_{mono_name[7:]}"
        media.append(media_entry(color_name, f"images/color/{filename}"))
        media.append(media_entry(mono_name, f"images/mono/{filename}"))
        common = row["common"].replace('"', '\\"')
        scientific = row["scientific"].replace('"', '\\"')
        inc_lines.append(
            f"  {{RESOURCE_ID_{color_name}, RESOURCE_ID_{mono_name}, "
            f'"{common}", "{scientific}"}},'
        )

    pkg = json.loads(PACKAGE.read_text(encoding="utf-8"))
    pkg["pebble"]["resources"]["media"] = media
    PACKAGE.write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8")

    count = len(rows)
    SPIDER_INC.write_text(
        "/* Generated by scripts/gen_spider_resources.py — do not edit by hand. */\n"
        "#ifndef SPIDER_TABLE_INC\n"
        "#define SPIDER_TABLE_INC\n"
        f"#define NUM_SPIDER {count}\n"
        "static const Spider SPIDER[NUM_SPIDER] = {\n"
        + "\n".join(inc_lines)
        + "\n};\n"
        "#endif\n",
        encoding="utf-8",
    )
    print(f"Wrote {count} spider families × 2 to {PACKAGE.name} and {SPIDER_INC.name}")


if __name__ == "__main__":
    main()